/** 경상북도 수신이면 공문 정산표의 마지막 열이 통장잔액이다(closeout-cover.md §2.6) */
/**
 * 공문 첫 줄 인사말 — 도는 "경상북도의", 군수는 "귀 군의", 시장은 "귀 시의"(담당자 공문 3629·400 "귀 군의 무궁한 발전을…"),
 * 그 밖의 기관은 "귀 기관의".
 */
export function greetingFor(recipient: string | undefined): string {
  if (isProvince(recipient)) return "경상북도의 무궁한 발전을 기원합니다.";
  if (recipient && /군수|군청/.test(recipient)) return "귀 군의 무궁한 발전을 기원합니다.";
  if (recipient && /시장|시청/.test(recipient)) return "귀 시의 무궁한 발전을 기원합니다.";
  return "귀 기관의 무궁한 발전을 기원합니다.";
}

function isProvince(recipient: string | undefined): boolean {
  return !!recipient && /경상북도|도지사/.test(recipient);
}

type Input = StagePromptInput & { brief: string; resume: string };

/**
 * 전년도 참고자료(prior/) — 계속사업은 같은 사업의 지난해 결과보고서가 있다(담당자 2026-10-22). 성과 분석만 읽고
 * 원장·결과·정산 단계는 읽지 않는다: 섞이면 지난해 지급 건이 원장에, 지난해 실적·총평이 올해 문서에 옮겨진다.
 */
const PRIOR_OFF_LIMITS = (ws: string) => `${ws}/prior/ 는 전년도 참고자료다 — 이 단계에서는 읽지 않는다(지난해 지급·실적이 올해 것에 섞인다).`;

function analysisPriorGuide(ws: string): string {
  return `${ws}/prior/index.md 가 있으면(전년도 참고자료 — 같은 사업의 지난해 결과보고서·정산보고서·계획서) 목록의 자료를 모두 읽는다. 쓰는 곳은 세 가지뿐이다.
   ① §2 전년 대비: 지원 규모·신청 수·선정 수·성과를 지난해 값과 한 쌍으로("'24년 3개사 → '25년 4개사 지정"). 같은 기준(신청·선정·지원 완료)끼리만 견준다.
   ② 지난해 「차년도 반영사항(개선 계획)」을 하나씩 올해 자료와 대조해 §4·§5 에 "이행 / 미이행 / 확인 필요"로 적는다 — 결재권자가 가장 먼저 묻는 것이다.
   ③ 세부사업 이름·구성·표 모양 참고(올해 계획서와 다르면 올해 계획서를 따른다).
   지난해 실적·사진·지급 건·날짜를 올해 것으로 쓰지 않는다. 지난해 문장(성과·총평)을 옮겨 적지 않는다 — 결과보고서에 같은 문장이 있으면 내보낼 때 경고가 뜬다. 근거는 [prior/파일명] 으로 단다.`;
}

/** 성과 분석에 붙이는 위키 안내 — 같은 사업의 전년도 결과가 있으면 전년 대비·차년도 반영의 근거가 된다 */
function analysisWikiGuide(wikiDir: string | undefined): string {
  if (!wikiDir) return "※ 내부 위키가 연결되지 않았다. 전년도 비교는 올린 자료에 전년 수치가 있을 때만 쓴다.";
  return `내부 위키(읽기 전용) ${wikiDir} 에서 같은 사업의 지난해 결과·계획을 Grep 으로 찾는다(사업명 핵심 낱말·세부사업 이름). 찾은 전년 수치(지원 규모·신청 수·성과)는 §2 의 전년 대비와 §5 차년도 반영사항의 근거로 쓰고, 출처 파일을 적는다. 찾지 못하면 "전년 자료 없음"으로 적고 지어내지 않는다.`;
}

